// Development-only generator. The game itself needs no canvas or external library.
// Rasterize the UNION of opaque SVG parts at 4x, then trace its boundary and
// simplify within 0.125 artwork units. Never trace or stroke individual parts.
const {chromium}=require('playwright');
const fs=require('node:fs');
const path=require('node:path');
const {createHash}=require('node:crypto');
const root=path.resolve(__dirname,'..');
(async()=>{
 const {artworks}=await import(path.join(root,'art.js'));
 const browser=await chromium.launch({headless:true,executablePath:process.env.CHROMIUM_PATH||'/usr/bin/chromium',args:['--no-sandbox']});
 try{
  const page=await browser.newPage();
  const outlines=await page.evaluate(async works=>{
   const scale=4,width=400*scale,height=300*scale,stride=width+1;
   const canvas=document.createElement('canvas');canvas.width=width;canvas.height=height;
   const ctx=canvas.getContext('2d',{willReadFrequently:true});const output={};
   // Iterative Douglas-Peucker: bounded deviation, not a fixed vertex count.
   function simplify(points){
    const keep=new Uint8Array(points.length);keep[0]=keep[points.length-1]=1;
    const stack=[[0,points.length-1]],epsilon=.5; // 0.125 SVG units at 4x.
    while(stack.length){const [start,end]=stack.pop(),a=points[start],b=points[end];let max=epsilon**2,index=-1;const dx=b[0]-a[0],dy=b[1]-a[1],len=dx*dx+dy*dy;
     for(let i=start+1;i<end;i++){const p=points[i],t=len?Math.max(0,Math.min(1,((p[0]-a[0])*dx+(p[1]-a[1])*dy)/len)):0;const d=(p[0]-a[0]-t*dx)**2+(p[1]-a[1]-t*dy)**2;if(d>max){max=d;index=i}}
     if(index!==-1){keep[index]=1;stack.push([start,index],[index,end])}
    }
    return points.filter((_,i)=>keep[i]);
   }
   for(const work of works){output[work.id]=[];
    for(let target=0;target<work.colors.length;target++){
     const parts=work.parts.filter(part=>part.color===target);
     const svg=`<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 400 300" width="${width}" height="${height}"><g fill="white" stroke="white" stroke-width="0">${parts.map(part=>part.shape).join('')}</g></svg>`;
     const url=URL.createObjectURL(new Blob([svg],{type:'image/svg+xml'}));const image=new Image();image.src=url;await image.decode();ctx.clearRect(0,0,width,height);ctx.drawImage(image,0,0);URL.revokeObjectURL(url);
     const pixels=ctx.getImageData(0,0,width,height).data;
     const inside=(x,y)=>x>=0&&y>=0&&x<width&&y<height&&pixels[(y*width+x)*4+3]>=128;
     const edges=new Map();
     const add=(x,y,x2,y2)=>{const key=y*stride+x,list=edges.get(key)||[];list.push(y2*stride+x2);edges.set(key,list)};
     for(let y=0;y<height;y++)for(let x=0;x<width;x++){if(!inside(x,y))continue;
      if(!inside(x,y-1))add(x,y,x+1,y);
      if(!inside(x+1,y))add(x+1,y,x+1,y+1);
      if(!inside(x,y+1))add(x+1,y+1,x,y+1);
      if(!inside(x-1,y))add(x,y+1,x,y);
     }
     const contours=[];
     while(edges.size){const start=edges.keys().next().value;let key=start;const points=[];
      do{points.push([key%stride,Math.floor(key/stride)]);const next=edges.get(key);if(!next)throw Error('Open silhouette boundary');const end=next.pop();if(!next.length)edges.delete(key);key=end}while(key!==start);
      points.push(points[0]);const reduced=simplify(points);
      contours.push('M'+reduced.slice(0,-1).map(p=>`${p[0]/scale} ${p[1]/scale}`).join('L')+'Z');
     }
     if(!contours.length)throw Error(`Empty silhouette: ${work.id}/${target}`);
     output[work.id].push(contours.join(''));
    }
   }
   return output;
  },artworks);
  const hash=createHash('sha256').update(JSON.stringify(artworks)).digest('hex');
  const text=`// Generated by tools/generate-outlines.cjs. Do not edit by hand.\n// Composite silhouettes; <= 0.125 unit simplification tolerance at 4x resolution.\nexport const outlineSourceHash='${hash}';\nexport const outlines=${JSON.stringify(outlines,null,2)};\n`;
  const filename=path.join(root,'outlines.js');
  if(process.argv.includes('--check')){if(fs.readFileSync(filename,'utf8')!==text)throw Error('outlines.js is stale; regenerate it')}else fs.writeFileSync(filename,text);
  console.log(`${process.argv.includes('--check')?'Verified':'Generated'} ${Object.values(outlines).reduce((n,v)=>n+v.length,0)} composite outlines for ${artworks.length} works`);
 }finally{await browser.close()}
})().catch(e=>{console.error(e);process.exit(1)});
